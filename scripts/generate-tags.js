function renderTagStarterLink(article, index) {
  return `<a href="${escapeAttr(article.url)}"><span>${String(index + 1).padStart(2, '0')}</span><strong>${escapeHtml(article.title)}</strong><em>${escapeHtml(article.category)}</em></a>`;
}

function renderStoryRow(article) {
  const meta = [article.category, article.readTime].filter(Boolean).join(' - ');
  return `        <article class="story-row">
          <span class="tag">${escapeHtml(article.category)}</span>
          <h3><a href="${escapeAttr(article.url)}">${escapeHtml(article.title)}</a></h3>
          <p>${escapeHtml(article.excerpt)}</p>
          ${meta ? `<small>${escapeHtml(meta)}</small>` : ''}
        </article>`;
}

function renderAdSlot(slotName, extraClass = '') {
  const className = ['ad-slot', extraClass].filter(Boolean).join(' ');
  return `<aside class="${escapeAttr(className)}" data-ad-slot="${escapeAttr(slotName)}" aria-label="Advertisement"><span>Advertisement</span></aside>`;
}

function renderStoryRowsWithMidAd(articles, slotName) {
  const rows = articles.map(renderStoryRow);
  if (rows.length >= 7) rows.splice(6, 0, renderAdSlot(slotName));
  return rows.join('\n');
}

