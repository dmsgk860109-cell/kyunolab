function normalizeNavPath(value) {
  const clean = String(value || '/').replace(/^https?:\/\/[^/]+/i, '').replace(/[?#].*$/, '');
  if (clean === '/' || clean === '') return '/';
  const withoutHtml = clean.replace(/\.html$/, '');
  return withoutHtml.endsWith('/') && withoutHtml !== '/' ? withoutHtml.slice(0, -1) : withoutHtml;
}

